#nullable enable
using System;

namespace EastFive.Configuration
{
    /// <summary>How a configuration member's absence is treated by the loader.</summary>
    public enum ConfigurationMemberKind
    {
        /// <summary>Absent is a configuration problem: the caller's <c>onMissing</c> decides.</summary>
        Required,

        /// <summary>Absent is a legitimate partial mode: the member is <c>null</c> in the typed
        /// config and the OPERATION that needs it reports not-configured.</summary>
        Optional,

        /// <summary>Absent applies <see cref="ConfigurationMemberAttribute.Default"/>, which is
        /// converted and validated like a read value.</summary>
        Defaulted,

        /// <summary>Secret material, read by the name <see cref="IProvideConfiguration.SecretReference"/>
        /// answers (generated by default, see <see cref="SecretNames"/>) and typed as
        /// <see cref="Secret"/>; confirmed-absent is <c>onMissing</c>, unreachable is
        /// <c>onSourceFailure</c>. Never defaulted, never substituted with an empty credential.</summary>
        Secret,
    }

    /// <summary>Whether a member's value differs per environment or is shared by all of them.</summary>
    public enum ConfigurationScope
    {
        /// <summary>Set per environment (a deployed environment must set its own).</summary>
        Environment,

        /// <summary>One value works everywhere; environments override only to tune.</summary>
        Shared,
    }

    /// <summary>How an editor renders a member. <see cref="Auto"/> derives it from the property type.</summary>
    public enum ConfigurationFieldKind
    {
        Auto,
        Text,
        Url,
        Number,
        Boolean,
        Duration,
        Enum,
        Secret,
        Account,
    }

    /// <summary>
    /// Declares one property of an <see cref="IProvideConfiguration"/> type as a configuration
    /// member: the values key it is read from, its <see cref="Kind"/>, the string-form
    /// <see cref="Default"/> for <see cref="ConfigurationMemberKind.Defaulted"/> members, and the
    /// <see cref="Purpose"/> a <see cref="ConfigurationMemberKind.Secret"/> member is resolved by.
    /// Members are processed in declaration order.
    /// </summary>
    /// <remarks>
    /// A secret member is declared WITHOUT a key (<c>[ConfigurationMember(Kind = Secret)]</c>): a
    /// secret is read from the secret store by its generated name, never from the values store.
    /// </remarks>
    [AttributeUsage(AttributeTargets.Property, AllowMultiple = false, Inherited = true)]
    public sealed class ConfigurationMemberAttribute : Attribute
    {
        /// <summary>A keyless member: a <see cref="ConfigurationMemberKind.Secret"/>.</summary>
        public ConfigurationMemberAttribute() { }

        public ConfigurationMemberAttribute(string key)
        {
            if (string.IsNullOrWhiteSpace(key))
                throw new ArgumentException("A configuration member needs a key.", nameof(key));
            Key = key;
        }

        /// <summary>The values key (e.g. <c>Email.SenderAddress</c>) the member is read from.
        /// <c>null</c> for a secret, which is read by name from the secret store.</summary>
        public string? Key { get; }

        /// <summary>This member's VALUE is the account id that scopes the type's secret names
        /// (<c>{Type}-{Account}-{Property}</c>). At most one per type; a string read from the
        /// values store, declared before every secret member.</summary>
        public bool Account { get; init; }

        public ConfigurationMemberKind Kind { get; init; } = ConfigurationMemberKind.Required;

        /// <summary>String form of the default (all config values originate as strings). Only
        /// meaningful with <see cref="ConfigurationMemberKind.Defaulted"/>.</summary>
        public string? Default { get; init; }

        /// <summary>A second key read only when <see cref="Key"/> is absent — a former spelling kept
        /// while deployments migrate. Never written by an editor; may carry the keyed placeholder.</summary>
        public string? FallbackKey { get; init; }

        /// <summary>Short human label for an editor (defaults to the property name).</summary>
        public string? Label { get; init; }

        /// <summary>What is provided by this value.</summary>
        public string? Description { get; init; }

        /// <summary>Where to find this value (portal blade, console page, launch argument).</summary>
        public string? Location { get; init; }

        /// <summary>More information: a link or a longer note.</summary>
        public string? MoreInfo { get; init; }

        /// <summary>Per-environment or shared; replaces the old deployment-override levels.</summary>
        public ConfigurationScope Scope { get; init; } = ConfigurationScope.Environment;

        /// <summary>How an editor renders the member; <see cref="ConfigurationFieldKind.Auto"/> derives it.</summary>
        public ConfigurationFieldKind FieldKind { get; init; } = ConfigurationFieldKind.Auto;

        /// <summary>What the secret is for, passed to <see cref="IProvideConfiguration.SecretReference"/>;
        /// defaults to the property name. Only meaningful with <see cref="ConfigurationMemberKind.Secret"/>.</summary>
        public string? Purpose { get; init; }
    }
}
